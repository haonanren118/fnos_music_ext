    calls: list[tuple] = []
    status_output = {
        "musicdl": "musicdl                        STOPPED   Not started",
        "musicbox": "musicbox                       RUNNING   pid 7, uptime 0:01:00",
        "lxmusic": "lxmusic                        STOPPED   Not started",
        "webui": "webui                          RUNNING   pid 8, uptime 0:01:00",
    }

    def fake(*args, timeout=20.0):
        calls.append(tuple(args))
        if args[0] == "status":
            # 真实 supervisorctl：存在 STOPPED 程序时退出码为 3（按需加载的常态）
            return 3, "\n".join(status_output.values())
        return 0, f"{args[0]}ed {args[1]}"

    monkeypatch.setattr(webui, "supervisorctl", fake)
    fake.calls = calls
    return fake


